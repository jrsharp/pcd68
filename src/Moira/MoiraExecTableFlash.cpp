// Helper function to get the exec pointer for a given opcode
// This implements the core instruction decoding logic from Moira's createJumpTables
static Moira::ExecPtr getExecPtrForOpcode(u16 opcode) {
    // MOVE.L #imm,SP (0x2E7C) - bootstrap instruction
    if (opcode == 0x2E7C) return &Moira::execMove2<MOVE, MODE_IM, Long>;

    // JMP absolute long (0x4EF9)
    if (opcode == 0x4EF9) return &Moira::execJmp<JMP, MODE_AL, Long>;

    // JSR absolute long (0x4EB9)
    if (opcode == 0x4EB9) return &Moira::execJsr<JSR, MODE_AL, Long>;

    // MOVEQ (0x7xxx pattern)
    if ((opcode & 0xF100) == 0x7000) return &Moira::execMoveq<MOVEQ, MODE_DN, Long>;

    // MOVE.W #imm,Dn (0x14xx pattern)
    if ((opcode & 0xFF00) == 0x1400) return &Moira::execMove0<MOVE, MODE_IM, Word>;

    // MOVEA.W #imm,An (0x3xxx with An destination)
    if ((opcode & 0xF000) == 0x3000 && (opcode & 0x01C0) == 0x0040) {
        return &Moira::execMovea<MOVEA, MODE_IM, Word>;
    }

    // MOVEA.L #imm,An (0x2xxx with An destination)
    if ((opcode & 0xF000) == 0x2000 && (opcode & 0x01C0) == 0x0040) {
        return &Moira::execMovea<MOVEA, MODE_IM, Long>;
    }

    // CMPI.L #imm,Dn (0x0C87 and similar)
    if ((opcode & 0xFF00) == 0x0C00) {
        u8 size_field = (opcode >> 6) & 0x3;
        u8 mode = (opcode >> 3) & 0x7;

        if (mode == 0) { // Data register direct
            switch (size_field) {
                case 0: return &Moira::execCmpiRg<CMPI, MODE_DN, Byte>;
                case 1: return &Moira::execCmpiRg<CMPI, MODE_DN, Word>;
                case 2: return &Moira::execCmpiRg<CMPI, MODE_DN, Long>;
            }
        }
    }

    // TODO: Add more instruction patterns as needed
    // For now, return execIllegal for unimplemented instructions
    return &Moira::execIllegal;
}

